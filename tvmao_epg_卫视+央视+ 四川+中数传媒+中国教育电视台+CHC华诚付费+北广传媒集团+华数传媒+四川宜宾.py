    def parse_page(self, html, target_date):
        if not html:
            return
        soup = BeautifulSoup(html, 'lxml')
        tables = soup.find_all('table', class_='timetable')
        for table in tables:
            for row in table.find_all('tr'):
                ch_cell = row.find('td', class_='tdchn')
                if not ch_cell:
                    continue
                link = ch_cell.find('a', class_='black_link')
                if not link:
                    continue
                href = link.get('href', '')
                ch_name = link.get_text(strip=True)
                ch_id = self._normalize_channel_id(href, ch_name)
                
                with self.lock:
                    if ch_id not in self.channels:
                        self.channels[ch_id] = ch_name
                
                for cell in row.find_all('td', class_='tdpro'):
                    title_div = cell.find('div', class_='font14')
                    if not title_div:
                        continue
                    title = title_div.get_text(strip=True)
                    time_div = cell.find('div', class_='font13')
                    if not time_div:
                        continue
                    time_text = time_div.get_text(strip=True)
                    m = re.match(r'(\d{1,2}):(\d{2})-(\d{1,2}):(\d{2})', time_text)
                    if not m:
                        continue
                    sh, sm, eh, em = map(int, m.groups())
                    start_d = target_date
                    end_d = target_date + timedelta(days=1) if (eh < sh or (eh == sh and em < sm)) else target_date
                    try:
                        start = start_d.replace(hour=sh, minute=sm)
                        end = end_d.replace(hour=eh, minute=em)
                        with self.lock:
                            self.programs.append({
                                'channel_id': ch_id,
                                'title': title.strip(),
                                'start': start,
                                'stop': end
                            })
                    except ValueError:
                        continue

    def crawl_day(self, day_offset=0):
        if not self.today_w:
            return 0
        target_w, target_date = self.get_w_and_date(day_offset)
        added = 0
        print(f"  [{self.province_id}] 抓取 今天 (w{target_w})")
        
        def fetch_hour(h):
            html = self.fetch_page(target_w, h)
            if html:
                before = len(self.programs)
                self.parse_page(html, target_date)
                return len(self.programs) - before
            return 0

        with ThreadPoolExecutor(max_workers=6) as executor:
            futures = [executor.submit(fetch_hour, h) for h in self.hour_blocks]
            for future in as_completed(futures):
                added += future.result()
            time.sleep(0.2)
        return added

    def crawl(self):
        print(f"\n=== 开始抓取 {self.province_id} (仅今日) ===")
        if not self.detect_today_w():
            return False
        self.crawl_day(0)
        print(f"✓ {self.province_id} 完成: {len(self.channels)} 频道, {len(self.programs)} 节目")
        return True

    def remove_duplicates(self):
        seen = set()
        unique = []
        for p in self.programs:
            key = (p['channel_id'], p['start'].strftime('%Y%m%d%H%M'))
            if key not in seen:
                seen.add(key)
                unique.append(p)
        self.programs = unique

    def generate_xmltv(self):
        self.remove_duplicates()
        root = ET.Element('tv')
        root.set('generator-info-name', 'tvmao-full-epg')
        
        id_mapping = {} # 用于将内部长ID映射为标准短ID
        
        for raw_id, ch_name in sorted(self.channels.items()):
            # 智能拆分逗号分隔的映射表
            if ',' in raw_id:
                parts = [p.strip() for p in raw_id.split(',') if p.strip()]
                true_id = parts[0]
                aliases = parts
            else:
                true_id = raw_id
                aliases = [raw_id]
            
            id_mapping[raw_id] = true_id
            
            ch = ET.SubElement(root, 'channel')
            ch.set('id', true_id)
            
            seen_names = set()
            # 1. 优先添加网页抓取的频道名称
            if ch_name:
                clean_name = clean_xml_text(ch_name)
                if clean_name and clean_name not in seen_names:
                    dn = ET.SubElement(ch, 'display-name')
                    dn.set('lang', 'zh')
                    dn.text = clean_name
                    seen_names.add(clean_name)
                    
            # 2. 添加所有别名 (提升 IPTV 匹配兼容性)
            for alias in aliases:
                clean_alias = clean_xml_text(alias)
                if clean_alias and clean_alias not in seen_names:
                    dn = ET.SubElement(ch, 'display-name')
                    dn.set('lang', 'zh')
                    dn.text = clean_alias
                    seen_names.add(clean_alias)

        # 节目单
        for p in sorted(self.programs, key=lambda x: (x['channel_id'], x['start'])):
            if not p['title']:
                continue
            
            true_ch_id = id_mapping.get(p['channel_id'], p['channel_id'])
            
            prog = ET.SubElement(root, 'programme')
            prog.set('start', p['start'].strftime('%Y%m%d%H%M%S +0800'))
            prog.set('stop', p['stop'].strftime('%Y%m%d%H%M%S +0800'))
            prog.set('channel', true_ch_id)
            
            title = ET.SubElement(prog, 'title')
            title.set('lang', 'zh')
            title.text = clean_xml_text(p['title'])
            
        return root

    def save(self, filename='epg.xml'):
        if not self.channels:
            return None
        os.makedirs(self.output_dir, exist_ok=True)
        root = self.generate_xmltv()
        
        # 格式化缩进
        indent_xml(root)
        
        xml_path = os.path.join(self.output_dir, filename)
        # 使用 ElementTree 原生写入，确保特殊字符(& < >)被完美转义
        tree = ET.ElementTree(root)
        tree.write(xml_path, encoding="utf-8", xml_declaration=True, method='xml')
        
        # 读取并注入标准的 DOCTYPE 声明
        with open(xml_path, 'r', encoding='utf-8') as f:
            content = f.read()
            
        if '<!DOCTYPE' not in content:
            content = content.replace('?>', '?>\n<!DOCTYPE tv SYSTEM "xmltv.dtd">', 1)
            
        with open(xml_path, 'w', encoding='utf-8') as f:
            f.write(content)
            
        # 生成 gzip 压缩版
        gz_path = xml_path + '.gz'
        with gzip.open(gz_path, 'wt', encoding='utf-8') as f:
            f.write(content)
            
        print(f"  保存完成: {xml_path} ({os.path.getsize(xml_path):,} bytes)")
        return xml_path

